-- OurBudget PostgreSQL schema. Source of truth: thesis database model.
-- Transfers are positive amounts with a destination_wallet_id; never add transactions_type.

CREATE TABLE public.users (
    users_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_name varchar(50) NOT NULL,
    users_password text,
    users_email varchar(150) NOT NULL UNIQUE,
    users_phonenumber varchar(10),
    users_avatar_url text,
    users_is_active smallint NOT NULL DEFAULT 1 CHECK (users_is_active IN (0, 1)),
    users_created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    users_updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    users_verified_at timestamp without time zone,
    user_google_sub varchar(255) UNIQUE,
    users_sessions_hash bytea UNIQUE CHECK (users_sessions_hash IS NULL OR octet_length(users_sessions_hash) = 32),
    users_sessions_expires_at timestamp without time zone,
    users_verification_hash bytea CHECK (users_verification_hash IS NULL OR octet_length(users_verification_hash) = 32),
    users_verification_experes_at timestamp without time zone,
    users_reset_hash bytea CHECK (users_reset_hash IS NULL OR octet_length(users_reset_hash) = 32),
    users_reset_expires_at timestamp without time zone,
    users_welcomed_at timestamp without time zone
);

CREATE TABLE public.wallet_categories (
    walletcates_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    walletcates_name varchar(150) NOT NULL UNIQUE,
    walletcates_icon varchar(150)
);

CREATE TABLE public.income_categories (
    income_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    income_name varchar(150) NOT NULL,
    income_icon varchar(150)
);

CREATE TABLE public.outcome_categories (
    outcome_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outcome_name varchar(150) NOT NULL,
    outcome_icon varchar(150)
);

CREATE TABLE public.wallets (
    wallets_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id integer NOT NULL REFERENCES public.users (users_id),
    walletcates_id bigint NOT NULL REFERENCES public.wallet_categories (walletcates_id),
    wallets_name varchar(100) NOT NULL,
    wallets_opening_balance bigint NOT NULL DEFAULT 0,
    wallets_current_balance bigint NOT NULL DEFAULT 0,
    wallets_priority smallint NOT NULL DEFAULT 0 CHECK (wallets_priority >= 0),
    wallets_is_active smallint NOT NULL DEFAULT 1 CHECK (wallets_is_active IN (0, 1)),
    wallets_created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    wallets_active_priority smallint GENERATED ALWAYS AS
        (CASE WHEN wallets_is_active = 1 THEN wallets_priority ELSE NULL END) STORED,
    UNIQUE (users_id, wallets_id),
    UNIQUE (users_id, wallets_active_priority)
);
CREATE INDEX ix_wallets_default
    ON public.wallets (users_id, wallets_is_active, wallets_priority, wallets_id);
CREATE INDEX ix_wallets_category ON public.wallets (walletcates_id);

CREATE TABLE public.transactions (
    transactions_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id integer NOT NULL REFERENCES public.users (users_id),
    wallets_id integer NOT NULL,
    destination_wallet_id integer,
    income_id bigint REFERENCES public.income_categories (income_id),
    outcome_id bigint REFERENCES public.outcome_categories (outcome_id),
    transactions_amount bigint NOT NULL,
    transactions_note text,
    transactions_occured_at timestamp without time zone NOT NULL,
    transactions_created_time timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    transactions_updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (users_id, wallets_id) REFERENCES public.wallets (users_id, wallets_id),
    FOREIGN KEY (users_id, destination_wallet_id) REFERENCES public.wallets (users_id, wallets_id),
    CONSTRAINT ck_transactions_shape CHECK (
        (transactions_amount > 0 AND income_id IS NOT NULL AND outcome_id IS NULL
            AND destination_wallet_id IS NULL)
        OR (transactions_amount < 0 AND outcome_id IS NOT NULL AND income_id IS NULL
            AND destination_wallet_id IS NULL)
        OR (transactions_amount > 0 AND income_id IS NULL AND outcome_id IS NULL
            AND destination_wallet_id IS NOT NULL AND destination_wallet_id <> wallets_id)
    )
);
CREATE INDEX ix_transactions_history
    ON public.transactions (users_id, transactions_occured_at, transactions_id);
CREATE INDEX ix_transactions_wallet_history
    ON public.transactions (users_id, wallets_id, transactions_occured_at, transactions_id);
CREATE INDEX ix_transactions_destination
    ON public.transactions (users_id, destination_wallet_id, transactions_occured_at, transactions_id);
CREATE INDEX ix_transactions_budget
    ON public.transactions (users_id, destination_wallet_id, outcome_id, transactions_occured_at);
CREATE INDEX ix_transactions_income ON public.transactions (income_id);
CREATE INDEX ix_transactions_outcome ON public.transactions (outcome_id);

CREATE TABLE public.budgets (
    budgets_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    users_id integer NOT NULL REFERENCES public.users (users_id),
    outcome_id bigint REFERENCES public.outcome_categories (outcome_id),
    income_id bigint REFERENCES public.income_categories (income_id),
    budgets_amount_limit numeric(19, 0) NOT NULL CHECK (budgets_amount_limit > 0),
    budgets_period varchar(5) NOT NULL CHECK (budgets_period IN ('WEEK', 'MONTH', 'YEAR')),
    budgets_start date NOT NULL,
    budgets_end date NOT NULL,
    budgets_created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_budgets_date_order CHECK (budgets_end >= budgets_start)
);
CREATE INDEX ix_budgets_user_period
    ON public.budgets (users_id, budgets_start, budgets_end);
CREATE INDEX ix_budgets_income ON public.budgets (income_id);
CREATE INDEX ix_budgets_outcome ON public.budgets (outcome_id);

CREATE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_TABLE_NAME = 'users' THEN
        NEW.users_updated_at := CURRENT_TIMESTAMP;
    ELSIF TG_TABLE_NAME = 'transactions' THEN
        NEW.transactions_updated_at := CURRENT_TIMESTAMP;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER users_set_updated_at
    BEFORE UPDATE ON public.users
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER transactions_set_updated_at
    BEFORE UPDATE ON public.transactions
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
REVOKE ALL ON FUNCTION public.set_updated_at() FROM PUBLIC, anon, authenticated;

